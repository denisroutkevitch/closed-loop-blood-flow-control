    %
    % Auto-generated by MATLAB on 28-Nov-2023 15:50:25
    
    % Input handling
    
    % If dataLines is not specified, define defaults
    if nargin < 2
        dataLines = [2, Inf];
    end
    
    % Set up the Import Options and import the data
    opts = delimitedTextImportOptions("NumVariables", 3);
    
    % Specify range and delimiter
    opts.DataLines = dataLines;
    opts.Delimiter = ";";
    
    % Specify column names and types
    opts.VariableNames = ["Time", "BP_drop", "cal_coef"];
    opts.VariableTypes = ["datetime", "double", "double"];
    
    % Specify file level properties
    opts.ExtraColumnsRule = "ignore";
    opts.EmptyLineRule = "read";
    
    % Specify variable properties
    opts = setvaropts(opts, "Time", "InputFormat", "yyyy-MM-dd HH:mm:ss.SSS");
    
    % Import the data
    tbl = readtable(filename, opts);
    
    % Convert to output type
    time = tbl.Time;
    vac_setting = round(tbl.BP_drop .* tbl.cal_coef/10);
    

end