    % IMPORT_RATCUUM Import data from a text file
    %  [TIME, VAC_SETTING] =
    %  IMPORT_RATCUUM(FILENAME) reads data from text file FILENAME for the
    %  default selection.  Returns the data as column vectors.
    %
    %  [TIME, VAC_SETTING] =
    %  IMPORT_RATCUUM(FILE, DATALINES) reads data for the specified row
    %  interval(s) of text file FILENAME. Specify DATALINES as a positive
    %  scalar integer or a N-by-2 array of positive scalar integers for
    %  dis-contiguous row intervals.
    %
    %  Example:
    %  [time, vac_setting] = import_ratcuum("/path/to/17-Nov-2023 Ratcuum.txt", [2, Inf]);
    %
